"""Honey for Hermes Agent: the always-on plugin.

Install: hermes plugins install Green-PT/honey-for-devs/.hermes

- Puts the compact Honey directive (COMPACT.md, the honey-chat core) into every new
  session's system prompt once, as a cache-safe section, so Honey is on without /honey.
- Registers every skill under skills/ as honey:<name> for skill_view.
- /honey [lite|full|ultra|off] pins a level. The section is frozen per session (prompt
  cache), so a pinned level adds one short line to each turn instead. The level lives in
  this process: it applies to every session the process serves and resets on restart.
- Entry-time GC for terminal output (honey-ccr): foreground output of the local terminal
  backend, 2,000 characters or more, is piped through hooks/logcompress-cli.js, which
  rewrites it only when the result is shorter and stashes the original in the temp folder
  first. The hook runs before Hermes redacts secrets, so it strips control sequences and
  applies Hermes' own redaction for that command first: the stash holds what the model
  would have seen. It needs `node`
  on PATH and is skipped without it; /honey off disables it. Any failure leaves the output
  unchanged.

No network. One short-lived `node` process per large terminal output; the only files
written are those stashes. Uninstall: hermes plugins remove honey.
This folder is generated by scripts/build-hermes-skills.js except this file.
"""

from __future__ import annotations

import logging
import re
import shutil
import subprocess
from pathlib import Path
from typing import Any, Mapping

ROOT = Path(__file__).resolve().parent
COMPACT = ROOT / "COMPACT.md"
SKILLS = ROOT / "skills"
LEVELS = ("lite", "full", "ultra")
DEFAULT_MODE = "full"
SECTION_ID = "honey.core"
SECTION_MAX_CHARS = 4000
GC_CLI = ROOT / "hooks" / "logcompress-cli.js"
GC_MIN_CHARS = 2000  # below this a process start costs more than a rewrite could save
GC_TIMEOUT_S = 5

_log = logging.getLogger(__name__)
_gc_failure_logged = False

_mode: str | None = None

_PINS = {
    "lite": "HONEY MODE PINNED: lite. Keep the explanation that is the deliverable; drop filler, hedging and narration.",
    "ultra": "HONEY MODE PINNED: ultra. Answer only, near-zero prose; still keep names, numbers, commands and one line on the main edge case.",
    "off": "HONEY MODE OFF. The Honey directive in the system prompt is suspended: answer normally.",
}


def frontmatter(text: str) -> dict[str, str]:
    """Flat `key: value` scalars of a SKILL.md frontmatter block (nested keys skipped)."""
    m = re.match(r"^---\r?\n([\s\S]*?)\r?\n---", text)
    out: dict[str, str] = {}
    for line in (m.group(1).splitlines() if m else []):
        key, sep, value = line.partition(":")
        if sep and key and not key[0].isspace():
            out[key.strip()] = value.strip().strip("\"'")
    return out


def skill_names() -> list[str]:
    return sorted(p.parent.name for p in SKILLS.glob("*/SKILL.md"))


def section_content(_session_info: Mapping[str, Any] | None = None) -> str:
    """The system-prompt section, rendered once per new session."""
    names = ", ".join(f"honey:{n}" for n in skill_names())
    return (
        "HONEY (I Shrunk the AI): always-on directive. Apply it as a writing style.\n\n"
        f"{COMPACT.read_text(encoding='utf-8').strip()}\n\n"
        f"Full skill and companions, loaded with skill_view (bare names do not resolve): {names}."
    )


def pin_line() -> str:
    return _PINS.get(_mode or DEFAULT_MODE, "")


def gc_terminal_output(output: str = "", command: str = "", env_type: str = "", **_: Any) -> str | None:
    """transform_terminal_output hook: the rewritten output, or None to leave it alone.
    What is rewritten is decided by hooks/logcompress-entry.js, the same code the Claude
    Code hook runs. Fail-open: no node, a timeout or an error returns None."""
    global _gc_failure_logged
    if _mode == "off" or not isinstance(output, str) or len(output) < GC_MIN_CHARS:
        return None
    # The stash and the restore command live on this machine. Another backend (docker, ssh)
    # cannot reach them, and background output arrives without its backend ("").
    if env_type != "local":
        return None
    # The restore command prints a stashed original: rewriting it again would hide it for good.
    if "eso.js" in command and "retrieve" in command:
        return None
    node = shutil.which("node")
    if not node or not GC_CLI.is_file():
        return None
    try:
        # This hook runs before Hermes' secret redaction, and how strict that is depends on
        # the command. Redact now, for this command and in Hermes' own order (control
        # sequences out first: a colour code inside `NAME=value` hides it from redaction),
        # so neither the stash nor a later restore holds more than the model would have
        # seen. Hermes repeats both steps afterwards; twice is harmless.
        from agent.redact import redact_terminal_output
        from tools.ansi_strip import strip_ansi
    except ImportError:
        return None
    try:
        output = redact_terminal_output(strip_ansi(output), command)
        # Bytes in and out: text mode would rewrite line endings on Windows.
        done = subprocess.run(
            [node, str(GC_CLI)],
            input=output.encode("utf-8"),
            capture_output=True,
            timeout=GC_TIMEOUT_S,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        view = done.stdout.decode("utf-8") if done.returncode == 0 else ""
    except Exception as exc:  # fail open: a hook must never break the terminal tool
        if not _gc_failure_logged:
            _gc_failure_logged = True
            _log.warning("honey: terminal-output GC skipped, output left unchanged (%s)", exc)
        return None
    return view if view and len(view) < len(output) else None


def handle_command(raw_args: str) -> str:
    global _mode
    arg = (raw_args or "").strip().lower()
    usage = f"Usage: /honey [{'|'.join(LEVELS)}|off]"
    if not arg:
        return f"Honey mode: {_mode or DEFAULT_MODE}. {usage}"
    if arg not in (*LEVELS, "off"):
        return usage
    _mode = arg
    if arg == "off":
        return "Honey off for this process: the system-prompt directive is suspended."
    return f"Honey mode set to {arg}."


def register(ctx: Any) -> None:
    """Entry point Hermes' plugin loader calls. Raises on a broken install: a plugin
    that loads without its directive or skills would look installed and do nothing."""
    if not COMPACT.is_file() or not skill_names():
        raise FileNotFoundError(f"Honey plugin files missing under {ROOT}; reinstall the plugin.")
    has_sections = hasattr(ctx, "register_system_prompt_section")
    if has_sections:
        ctx.register_system_prompt_section(
            SECTION_ID, section_content, position="after_memory", max_chars=SECTION_MAX_CHARS
        )

    def pre_llm_call(is_first_turn: bool = False, **_: Any) -> dict[str, str] | None:
        # Hermes before cache-safe sections: carry the directive on each session's first turn.
        first = is_first_turn and not has_sections and _mode != "off"
        parts = [section_content()] if first else []
        if pin_line():
            parts.append(pin_line())
        return {"context": "\n\n".join(parts)} if parts else None

    ctx.register_hook("pre_llm_call", pre_llm_call)
    ctx.register_hook("transform_terminal_output", gc_terminal_output)
    ctx.register_command(
        "honey",
        handle_command,
        description="Set the Honey level: lite, full, ultra or off.",
        args_hint="[lite|full|ultra|off]",
    )
    for name in skill_names():
        path = SKILLS / name / "SKILL.md"
        meta = frontmatter(path.read_text(encoding="utf-8"))
        ctx.register_skill(name, path, description=meta.get("description", ""))
